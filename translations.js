(function () {
  const button = document.getElementById('language-toggle');
  if (!button) return;
  const richKeys = new Set(["aboutIntro", "contactTitle", "heroTitle"]);
  const attrTranslations = {
    pt: { themeLabel: 'Alternar tema', pegaVideoLabel: 'Demonstração do Software PEGA', ozoneLogoAlt: 'Logo do Projeto O3 Mover', githubImageAlt: 'Atividades do GitHub de João Pedro Magri' },
    en: { themeLabel: 'Toggle theme', pegaVideoLabel: 'PEGA software demonstration', ozoneLogoAlt: 'O3 Mover Project logo', githubImageAlt: 'João Pedro Magri GitHub activity' }
  };
  let language = 'pt';
  try { language = localStorage.getItem('language') === 'en' ? 'en' : 'pt'; } catch (_) {}
  function applyLanguage(lang) {
    language = lang;
    document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (Object.prototype.hasOwnProperty.call(translations[lang], key)) el.textContent = translations[lang][key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.dataset.i18nHtml;
      if (richKeys.has(key) && Object.prototype.hasOwnProperty.call(translations[lang], key)) el.innerHTML = translations[lang][key];
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      el.dataset.i18nAttr.split(';').forEach(item => {
        const [key, attr] = item.split(':');
        if (attr && Object.prototype.hasOwnProperty.call(attrTranslations[lang], key)) el.setAttribute(attr, attrTranslations[lang][key]);
      });
    });
    button.textContent = lang === 'pt' ? '🇺🇸' : '🇧🇷';
    button.title = lang === 'pt' ? 'Switch to English' : 'Mudar para português';
    button.setAttribute('aria-label', button.title);
    try { localStorage.setItem('language', lang); } catch (_) {}
  }
  button.addEventListener('click', () => applyLanguage(language === 'pt' ? 'en' : 'pt'));
  applyLanguage(language);
})();
